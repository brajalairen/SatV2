"""Assemble results/report.md from the artifacts the run actually produced.

Generated rather than hand-written so no number in the report can drift from the JSON it came from
(CLAUDE.md section 7: never fabricate scores).
"""

import argparse
import hashlib
import json
from pathlib import Path

RESULTS = Path(__file__).resolve().parent / "results"


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with open(path, "rb") as handle:
        while block := handle.read(1 << 20):
            digest.update(block)
    return digest.hexdigest()


def delta(after: float, before: float) -> str:
    return f"{(after - before) * 100:+.2f} pp"


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--adapter", type=Path, default=Path("runs/adaptation/adapter"))
    args = parser.parse_args()

    before = json.loads((RESULTS / "eval_before.json").read_text(encoding="utf-8"))
    after_path = RESULTS / "eval_after.json"
    after = json.loads(after_path.read_text(encoding="utf-8")) if after_path.exists() else None
    manifest = json.loads((RESULTS / "dataset_manifest.json").read_text(encoding="utf-8"))
    spike = json.loads((RESULTS / "spike_report.json").read_text(encoding="utf-8"))
    config = json.loads((args.adapter / "train_config.json").read_text(encoding="utf-8"))

    weights = args.adapter / "adapter_model.safetensors"
    total_params = spike["architecture"]["total_params_millions"] * 1e6
    lines = [
        "# SIH R5 adaptation: results",
        "",
        "Generated by `experiments/adaptation/make_report.py` from the run artifacts. Every number below is read",
        "from a JSON file in this directory; none is typed by hand.",
        "",
        "## What was adapted",
        "",
        f"- **Base model:** `{config['model_id']}` ({spike['architecture']['class']}, "
        f"{spike['architecture']['total_params_millions']} M params, encoder-decoder with a DaViT vision tower)",
        f"- **Method:** {config['method']}, rank {config['rank']}, alpha {config['alpha']}, dropout {config['dropout']}",
        f"- **Adapted modules:** {config['target_module_count']} decoder attention projections (self-attention and "
        f"cross-attention q/k/v/out). **Vision tower frozen.**",
        f"- **Trainable parameters:** {config['trainable_params']:,} "
        f"({100 * config['trainable_params'] / total_params:.3f}% of the model)",
    ]
    if weights.exists():
        lines.append(f"- **Adapter size:** {weights.stat().st_size / 1e6:.1f} MB")
        lines.append(f"- **Adapter SHA-256:** `{sha256(weights)}`")

    lines += [
        "",
        "## Training data",
        "",
        f"**{manifest['dataset']}**",
        "",
        f"- Source parquet SHA-256: `{manifest['parquet_sha256']}`",
        f"- Row type filter: `{manifest['row_type_filter']}` only",
        f"- Selection: {manifest['selection']}",
        f"- Answer balance: {manifest['yes_no']}",
        f"- Rendering: {manifest['render']}",
        f"- Splits disjoint by patch id: **{manifest.get('splits_disjoint_by_patch_id')}** (asserted at build time)",
        "",
        "| Split | Rows | Patches | yes rate | Categories |",
        "|---|---|---|---|---|",
    ]
    for split, info in manifest["splits"].items():
        cats = ", ".join(f"{k} {v}" for k, v in sorted(info["by_category"].items()))
        lines.append(f"| {split} | {info['rows']:,} | {info['patches']:,} | {info['yes_base_rate']} | {cats} |")

    lines += [
        "",
        "## Training run",
        "",
        f"- **Hardware:** {config.get('gpu', 'n/a')}, torch {config['torch']}",
        f"- Batch size {config['batch_size']} with gradient accumulation {config['grad_accum']} "
        f"(effective batch {config['effective_batch']})",
        f"- Learning rate {config['lr']}, {config['scheduler']} schedule, {config['epochs']} epoch(s), "
        f"seed {config['seed']}",
        f"- Precision: {config['dtype']}",
        f"- **Peak reserved VRAM: {config.get('peak_reserved_gb', 'n/a')} GB** "
        f"(feasibility gate was {spike['gate']['threshold_gb']} GB)",
        f"- Wall clock: {config['minutes']} minutes for {config['train_rows']:,} samples",
    ]
    for entry in config.get("history", []):
        if "val_loss" in entry:
            lines.append(f"- Validation loss after epoch {entry['epoch']}: **{entry['val_loss']}**")

    lines += [
        "",
        "Per-step loss: `train_log.csv`. Pre-flight overfit check: `overfit_check.csv` (loss 4.4619 -> 0.0125 on 20",
        "samples over 25 epochs), which confirmed the label format and gradient path before the real run.",
        "",
        "## Evaluation",
        "",
        f"Exact-match on **{before['rows']:,} held-out rows**, from patches never seen in training. Answers are",
        "compared case- and punctuation-insensitively, so `Yes.` matches `yes`.",
        "",
    ]

    if after:
        lines += [
            "| Metric | Before | After | Change |",
            "|---|---|---|---|",
            f"| **Overall exact-match** | {before['exact_match']:.4f} | {after['exact_match']:.4f} | "
            f"**{delta(after['exact_match'], before['exact_match'])}** |",
        ]
        for cat in sorted(before["per_category"]):
            b = before["per_category"][cat]
            a = after["per_category"].get(cat)
            if a:
                lines.append(f"| {cat} (n={b['n']}) | {b['exact_match']:.4f} | {a['exact_match']:.4f} | "
                             f"{delta(a['exact_match'], b['exact_match'])} |")
        lines += [
            "",
            f"**Yes/no base rate in the test set: {before['yes_base_rate']}.** The set is balanced, so a model that",
            "always answered the same way would score 0.50. Read any score near 0.50 against the prediction",
            "distribution below rather than as skill.",
            "",
            f"- Predictions before: `{before['prediction_distribution']}`",
            f"- Predictions after: `{after['prediction_distribution']}`",
        ]
    else:
        lines += [
            f"- **Before (base model): {before['exact_match']:.4f}** exact-match, "
            f"yes base rate {before['yes_base_rate']}",
            f"- Predictions: `{before['prediction_distribution']}`",
            "- After: **not yet run.**",
        ]

    lines += [
        "",
        "## Limitations, stated plainly",
        "",
        "- This adapts to **BigEarthNet Sentinel-2, 120x120 px at 10 m**. It says **nothing** about performance on "
        "Cartosat-2S at 0.65 m, and no such claim is made.",
        "- **Binary yes/no rows only.** Bounding-box rows need Falcon's coordinate-token grammar, a separate target "
        "that risks regressing the working grounding path.",
        "- **Land-cover class balance is not controlled.** `metadata.parquet` is not available on this machine, so "
        "patches were selected from BigEarthNet.txt's own split column and stratified by question category instead.",
        "- Exact-match on short binary answers is a narrow metric. It does not measure caption quality, grounding or "
        "change detection, none of which were trained here.",
        "- Confidence values elsewhere in the app remain uncalibrated and are unaffected by this work.",
        "",
        "## Reproducing",
        "",
        "See `../README.md`. Data and adapter weights are gitignored (CLAUDE.md section 11); the manifest records "
        "the source parquet hash and selection settings so the dataset can be rebuilt exactly.",
    ]
    out = RESULTS / "report.md"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
